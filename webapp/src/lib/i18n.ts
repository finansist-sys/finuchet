export type Lang = "ru" | "en";
export const dicts: Record<Lang, Dict> = { ru: ru as Dict, en };

export function langOf(code: string | undefined): Lang {
  return !code || /^(ru|uk|be|kk)/i.test(code) ? "ru" : "en";
}

const MONTHS_RU_PREP = ["январе", "феврале", "марте", "апреле", "мае", "июне", "июле", "августе", "сентябре", "октябре", "ноябре", "декабре"];
const MONTHS_RU = ["Январь", "Февраль", "Март", "Апрель", "Май", "Июнь", "Июль", "Август", "Сентябрь", "Октябрь", "Ноябрь", "Декабрь"];
const MONTHS_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

export function monthName(lang: Lang, month: number, prepositional = false): string {
  if (lang === "en") return MONTHS_EN[month];
  return prepositional ? MONTHS_RU_PREP[month] : MONTHS_RU[month];
}

export function weekdayShort(lang: Lang, i: number): string {
  return (lang === "ru" ? ["пн", "вт", "ср", "чт", "пт", "сб", "вс"] : ["Mo", "Tu", "We", "Th", "Fr", "Sa", "Su"])[i];
}

export function dayLabel(lang: Lang, d: Date, today: Date): string {
  const sameDay = (a: Date, b: Date) => a.toDateString() === b.toDateString();
  const y = new Date(today);
  y.setDate(today.getDate() - 1);
  if (sameDay(d, today)) return dicts[lang].today;
  if (sameDay(d, y)) return dicts[lang].yesterday;
  return d.toLocaleDateString(lang === "ru" ? "ru-RU" : "en-GB", {
    day: "numeric",
    month: "long",
    ...(d.getFullYear() !== today.getFullYear() ? { year: "numeric" } : {}),
  });
}
